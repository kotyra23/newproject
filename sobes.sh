Брокеры хранят **Топики**. Топики делятся на **Партиции** (partitions) для параллелизма. Продюсеры пишут сообщения, консьюмеры читают. Репликация партиций обеспечивает отказоустойчивость.

### № 14. Проблема базы данных Prometheus?
Хранит все в памяти и на диске. При высоких нагрузках или долгих ретеншенах (retention) может "съесть" весь диск или RAM. Требует тщательного тюнинга и использования Thanos/Cortex для масштабирования.

### № 67. Что такое ключ в базе данных?
Атрибут (или группа), уникально идентифицирующий строку (Primary Key) и служащий для связи таблиц (Foreign Key).

### № 68. Как защититься от прерывания команды SQL?
Использовать транзакции (`BEGIN`, `COMMIT`, `ROLLBACK`). Если что-то пойдет не так, транзакция откатится.

### № 69. Как увеличить скорость чтения таблицы?
Создавать индексы (B-Tree) для колонок, используемых в `WHERE`, `ORDER BY`, `JOIN`.

### № 131. При обновлении версии приложения функционал начал тормозить?
1. Появились медленные SQL-запросы (отсутствует индекс).
2. Таблица заблокирована (deadlock).
3. Добавились тяжелые зависимости или изменилась логика кэширования.
