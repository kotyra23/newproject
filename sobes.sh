# 🌐 Networking & Security

### № 2. Выявил проблему доступности сети, как бы ты это дебажил?
1. Поднят ли интерфейс: `ip addr show`.
2. Идут ли пакеты: `ping -c 4 8.8.8.8`.
3. Доступность портов: `ss -tulnp`.
4. Правила файрвола: `iptables -L -n -v` или `ufw status`.

### № 18. MX запись в DNS что это?
Mail Exchange. Указывает на почтовый сервер, который отвечает за прием писем для данного домена.

### № 23. Почему VPN плох для подключения пользователей к машинам?
Классический VPN дает доступ ко всей внутренней инфраструктуре (широкий доступ). Лучше использовать Zero Trust / Bastion-хосты.

### № 24. Какие порты открываются при VPN подключении?
Чаще всего UDP (например, 1194 для OpenVPN, 51820 для WireGuard).

### № 25. Если интернет слабый, а нужно обрабатывать запросы и фильтровать?
Разделить задачи: вынести фильтрацию (WAF / Reverse Proxy) на отдельный сервер или CDN, чтобы не нагружать основной бэкенд.

### № 26. Zero Trust Access как работает?
Принцип "Никому не доверяй, проверяй всё". Каждый запрос аутентифицируется и авторизуется отдельно, доступ дается по принципу наименьших привилегий.

### № 28. DMZ в роутинге?
Изолированная подсеть между локальной и глобальной сетью, где размещаются публичные сервисы (веб-сервера, шлюзы).

### № 30. Деплоить приложение как процесс или в контейнере при высокой нагрузке?
Процесс быстрее стартует и жрет меньше ресурсов, но сложнее масштабируется и изолируется. Контейнер чуть медленнее, но идеально подходит для оркестрации и масштабирования.

### № 31. Как настраивается система NAT в Docker?
Создается виртуальный мост (`docker0`), назначается IP контейнеру, и `iptables` автоматически настраивает правила MASQUERADE для NAT.

### № 33. Борьба с фишингом?
Настройка SPF, DKIM, DMARC записей для домена; фильтрация входящего трафика; использование WAF.

### № 42. Для чего нужна маска подсети?
Разделяет IP-адрес на адрес сети и адрес хоста. Помогает маршрутизатору понять, пакет локальный или его нужно отправлять через шлюз (NAT).

### № 43. Разница публичных и приватных адресов?
**Публичный** — глобально уникален, маршрутизируется в интернете. **Приватный** (RFC 1918) — уникален только внутри локальной сети, выход в интернет только через NAT.

### № 44. Как провайдер определяет, кому отправить пакет?
По IP-адресу назначения в заголовке. Далее смотрит в таблицу маршрутизации (BGP, статические маршруты) для выбора следующего хопа.

### № 45. Как резолвится имя хоста?
1. Локальная проверка в `/etc/hosts`.
2. Запрос к локальному DNS-резолверу.
3. Рекурсивный запрос к корневым, TLD и авторитетным серверам.
4. Возврат IP-адреса клиенту.

### № 46. По какому протоколу работает DNS?
В основном UDP (порт 53). TCP используется, если ответ больше 512 байт или для зонной трансфер (AXFR).

### № 47. Проблема безопасности в рамках DNS?
Классический DNS не шифруется (подмена ответов, spoofing). Решение: DNSSEC (криптографическая подпись) и DoH/DoT (шифрование).

### № 60. Стек TCP/IP?
4 уровня: Прикладной (HTTP), Транспортный (TCP/UDP), Сетевой (IP), Канальный (MAC/Ethernet).

### № 61. Отличия TCP от UDP?
**TCP** — надежный, с установлением соединения, гарантирует доставку и порядок. **UDP** — "дешевый", без гарантий, быстрый, подходит для стриминга и DNS.

### № 62. Как TCP устанавливает соединение?
Three-way handshake: Клиент -> SYN, Сервер -> SYN+ACK, Клиент -> ACK.

### № 63. Обязательно ли хост должен ответить на ping?
Нет. На хосте может быть настроен firewall (drop ICMP) или отключен ICMP в ядре (`icmp_echo_ignore_all`).

### № 64. Сервер получил неправильный IP-адрес, о чем это говорит?
Сервер не достучался до DHCP (получил APIPA 169.254.x.x) или в сети конфликт IP-адресов.

### № 65. Как работает DHCP?
Поверх UDP. DORA: Discover (клиент ищет), Offer (сервер предлагает), Request (клиент запрашивает), Acknowledge (сервер подтверждает).

### № 66. Что такое NAT?
Network Address Translation. Механизм подмены IP-адресов (SNAT/DNAT) в заголовках пакетов при прохождении через маршрутизатор.

### № 70. Что такое HTTP протокол?
Протокол прикладного уровня для обмена данными между клиентом и сервером по модели запрос-ответ.

### № 71. Методы HTTP?
GET (получить), POST (создать), PUT (заменить полностью), PATCH (обновить частично), DELETE (удалить), HEAD (только заголовки).

### № 72. Коды ответа HTTP?
1xx (Информационные), 2xx (Успех, 200 OK), 3xx (Перенаправления), 4xx (Ошибка клиента, 404, 400), 5xx (Ошибка сервера, 500, 502).

### № 73. Версии протокола HTTP?
HTTP/1.0, HTTP/1.1 (keep-alive), HTTP/2.0 (мультиплексирование), HTTP/3.0 (поверх QUIC/UDP).

### № 74. Как устанавливается соединение HTTPS?
TLS Handshake: обмен версиями и шифрами, проверка сертификата сервера, генерация симметричного сессионного ключа.

### № 92. Чем TCP поддерживает соединение?
Через ACK-подтверждения и механизм скользящего окна (flow control), а также отправляет пустые пакеты (keep-alive).

### № 93. Чем симметричное шифрование отличается от асимметричного?
**Симметричное** — один ключ для шифрования и расшифровки (быстрое). **Асимметричное** — пара ключей (публичный и приватный), используется для обмена симметричным ключом.

### № 94. Как работает ICMP?
Инкапсулируется прямо в IP-пакет (без портов). Служит для диагностики (ping) и отправки сообщений об ошибках (Destination Unreachable).

### № 123. Как посмотреть маршрут пакетов?
`ip route` (таблица маршрутизации) или `traceroute / mtr` (трассировка до цели).

### № 124. Что такое TTL?
Time To Live. Счетчик в IP-пакете, уменьшается на 1 при прохождении каждого роутера. Защищает от петель маршрутизации.

### № 125. Замер пропускной способности?
Утилита `iperf3 -c <server_ip>`.

### № 126. Если TCP соединение разорвется, пакет доставится?
Гарантия доставки работает только в рамках установленной сессии. Если сессия разорвана (RST), новые пакеты отклонятся.

### № 127. Плюсы HTTPS помимо шифрования?
Аутентификация сервера (доверие к сертификату) и целостность данных (защита от подмены "на лету").

### № 128. Типы заголовков HTTP?
General (общие), Request (запроса), Response (ответа), Entity (сущности/тела).
