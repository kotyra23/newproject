# 🐧 Linux & OS

### № 1. Если сервис в Линуксе упал, как починить?
Сначала диагностика через `du -h`, `ps aux`, `top`. Потом `systemctl restart <service>`.

### № 3. Как посмотреть диски по заполняемости?
Команда `df -h`.

### № 13. Как бы ты обезопасил ВМ?
Вход только по SSH-ключам; настройка входящего и исходящего трафика через `iptables`; ограничение прав доступа к директориям.

### № 19. Если сервер не отвечает на ping, что делать?
Проверить firewall (возможно, стоит запрет на входящий трафик). Также проверить ядро (настройки `sysctl`), не отключены ли ICMP-протоколы для диагностики.

### № 20. Типы сообщений в ICMP протоколе?
Reply, Request, Error message, Time exceeded.

### № 21. Сбор информации с хоста, если нет интернета?
Сеть: `ip addr show`, `ip route`. Порты: `ss -tulnp`. Процессы: `ps aux`, `top`.

### № 22. Как разработчики подключаются к Линуксовым ВМ?
1. **SSH-ключи** — стандарт, публичный ключ в `~/.ssh/authorized_keys`.
2. **Teleport / Bastion-хост** — централизованный доступ с MFA и записью сессий.
3. **VPN** — устаревший подход (слишком широкий доступ).
4. **SSM Session Manager (AWS)** — без SSH-портов, через IAM.

Best practice: запретить парольную аутентификацию (`PasswordAuthentication no` в `sshd_config`).

### № 29. Что такое контейнер?
Это изолированный процесс, который делит с хостом его ресурсы (ядро, cgroups, namespaces).

### № 34. Какие утилиты часто используешь в Линуксе?
`top`, `iptables`, `ps aux`, `ss`, `ip`, `journalctl`, `chmod`.

### № 36. Как сделать, чтобы софт из кода крутился 24/7?
Через `systemd`. Создаю unit-файл и включаю через `systemctl enable`.

### № 37. Какой type необходимо указать, чтобы в systemd не летело все в терминал?
`simple` (или `forking` / `notify` в зависимости от демона, но `simple` — базовый).

### № 38. Что делать если приложение само завершилось?
Анализ через `journalctl` или, если это контейнер, через `docker logs`.

### № 39. Почему ping можно запустить без sudo?
На бинарнике установлен бит `setuid` (или capabilities `cap_net_raw`), что дает специальные привилегии.

### № 55. Этапы загрузки Linux?
1. BIOS/UEFI (проверка железа).
2. Загрузчик (GRUB, загружает ядро).
3. Ядро инициализирует драйверы и монтирует корневую файловую систему (rootfs).

### № 56. Сервер лагает, анализ производительности?
Смотреть `htop`, у какого процесса сильнее потребление CPU/RAM. Далее смотреть логи конкретного сервиса через `journalctl`.

### № 57. Что такое load average?
Это среднее количество процессов, запущенных или ожидающих выполнения (CPU или Disk I/O), за последние 1, 5 и 15 минут.

### № 58. Как можно дебажить приложение, которое не пишет логи и нет доступа к конфигам?
Через `strace -p <PID>` — покажет, к каким файлам и системным вызовам обращается процесс.

### № 59. Как процессы могут общаться между собой (IPC)?
Через сигналы, через сокеты (Unix domain sockets), через разделяемую память (shared memory), каналы (pipes).

### № 85. Высокий load average?
Посмотреть через `htop`. Если много процессов в состоянии `D` (непрерывный сон), возможно, проблема с дисками — проверяем через `iostat`.

### № 87. Если завис процесс, в чем проблема?
Проверить статус через `ps -o stat`. Если статус `D` — процесс ждет ответа от диска (I/O wait).

### № 88. Как работает OOM Killer и для чего он нужен?
Когда системе не хватает памяти (Out Of Memory), ядро убивает процессы, чтобы спасти систему от полного зависания.

### № 91. Отличие хардлинков от симлинков?
Хардлинк — это еще одна ссылка на inode файла (копия на уровне файловой системы). Симлинк — это ярлык, содержащий путь к исходному файлу.

### № 103. Что такое системные вызовы?
Механизм, через который приложение запрашивает услуги у ядра ОС (выделение памяти, чтение файла, сетевые запросы).

### № 104. Что такое виртуализация?
Абстракция от аппаратуры с целью создания изолированных сред (ВМ), каждая из которых имеет свою ОС.

### № 111. Что такое LVM?
Logical Volume Manager — слой абстракции для управления дисками, позволяющий динамически менять размеры разделов и объединять диски.

### № 129. Порт в Линуксе? Зомби-процесс?
**Порт** — логический идентификатор сетевого соединения на машине. 
**Зомби** — дочерний процесс, который завершил выполнение, но родитель не считал его код выхода (не вызвал `wait()`).

### № 134. Опыт работы в iptables?
Фильтрация и маршрутизация трафика. Работает как stateful firewall с цепочками правил (INPUT, OUTPUT, FORWARD) на вход и выход.
