# ☸️ Kubernetes

### № 5. Как происходит синхронизация мастер-ноды и воркера?
Мастер (apiserver) отдает команды, `kubelet` на воркере слушает apiserver и управляет контейнерами через CRI (Container Runtime).

### № 9. Способы развертывания в Kubernetes?
`kubectl apply` (сырые манифесты), `Helm` (пакетный менеджер), GitOps (ArgoCD / Flux).

### № 10. Отличия StatefulSet от Deployment?
**StatefulSet** — для приложений с состоянием (БД), важен порядок запуска, стабильные сетевые идентификаторы и персистентные тома. **Deployment** — для stateless приложений, поды взаимозаменяемы.

### № 11. Какие приложения в k8s разворачивал?
Node.js, Express, MongoDB, Flask (Python).

### № 17. Самая сложная задача?
Развертывание кластера k8s в Yandex Cloud с настройкой кастомной CNI-сети для узлов кластера.

### № 27. Разница между пробами в k8s?
- **Liveness probe** — жив ли под? (если нет — рестарт).
- **Readiness probe** — готов ли под принимать трафик? (если нет — убрать из Service).
- **Startup probe** — запустился ли под? (нужна для медленных приложений, блокирует остальные пробы).

### № 90. Что такое Readiness, Liveness, Startup пробы?
*(Дублирует №27)* Механизмы управления жизненным циклом. Liveness — перезапуск при зависании, Readiness — балансировка трафика, Startup — защита от преждевременного рестарта.

### № 95. DaemonSet зачем он нужен?
Контроллер, который гарантирует запуск ровно одного пода на каждой ноде кластера (например, для сборщиков логов Fluentd или мониторинга Node Exporter).

### № 96. Что такое Taints, Tolerations?
**Taints** (на ноде) — "отпугивают" поды. **Tolerations** (на поде) — "разрешают" поду сесть на ноду с таким taint'ом.

### № 97. Что такое Requests, Limits?
**Requests** — гарантия ресурсов, учитывается планировщиком (scheduler). **Limits** — жесткий потолок (если превышен CPU — троттлинг, если RAM — OOMKilled).

### № 98. Что такое Affinity и Anti-affinity?
**Affinity** — притягивать поды к определенным нодам (или другим подам). **Anti-affinity** — разбрасывать поды подальше друг от друга (для отказоустойчивости).

### № 102. Что такое узел, нода?
Кластер состоит из узлов (nodes). Нода — это физическая или виртуальная машина (воркер или мастер).

### № 105. Что такое ReplicaSet? Что такое Deployment?
**ReplicaSet** — контроллер, поддерживающий заданное количество реплик подов. **Deployment** — более высокоуровневый контроллер, который управляет ReplicaSet'ами (обновления, откаты).

### № 106. Что такое Service в кубере?
Абстракция, предоставляющая стабильный IP и DNS для группы подов. Типы: ClusterIP (внутри кластера), NodePort (порт на ноде), LoadBalancer (внешний балансировщик), ExternalName.

### № 107. Что такое Ingress?
API-объект для управления внешним HTTP/HTTPS доступом. Маршрутизирует трафик к сервисам по правилам (Host, Path).

### № 108. Что такое Job?
Контроллер для запуска одноразовых задач. Запускает поды, ждет их успешного завершения и останавливается.

### № 109. Что означает apiVersion?
Определяет схему данных и стабильность API (например, `apps/v1`, `v1`, `batch/v1`).

### № 110. Что такое Namespaces?
Механизм логической изоляции ресурсов внутри одного физического кластера (например, `dev`, `prod`, `monitoring`).

### № 114. В k8s ошибка CrashLoopBackOff?
