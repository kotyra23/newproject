# 🔄 CI/CD, Git & DevOps Practices

### № 40. Инфраструктура как код (IaC), как понимаешь?
Описание инфраструктуры (серверы, сети) в коде (Terraform, Ansible). Позволяет версионировать, отслеживать изменения через Git и быстро откатывать/воспроизводить среды.

### № 41. Что такое CI/CD?
**CI (Continuous Integration)** — автоматическая сборка, линтинг и тестирование при пуше кода.
**CD (Continuous Delivery/Deployment)** — автоматическая доставка и деплой артефакта в прод (или ручной релиз по кнопке).

### № 48. Зачем нужен DevOps?
Для ускорения и надежной доставки кода от разработчика до пользователя, автоматизации рутины и стирания границ между Dev и Ops.

### № 49. Самая важная DevOps практика?
CI/CD и Infrastructure as Code (IaC).

### № 50. Инструменты для развертывания окружения и настройки?
**Terraform** — создание облачной инфраструктуры (Provisioning). **Ansible** — настройка ОС и софта внутри серверов (Configuration Management).

### № 51. Что лучше: push-модель или pull-модель?
**Pull** (например, ArgoCD) лучше для k8s, так как кластер сам "вытягивает" изменения из Git. **Push** (Ansible) удобен для конфигурации "железных" ВМ.

### № 52. Этапы работы в Ansible?
1. **Inventory** — описываем список серверов.
2. **Playbook** — пишем YAML-сценарии (роли, задачи).
3. **Execution** — запускаем `ansible-playbook`.
4. **Idempotency** — Ansible проверяет состояние и применяет изменения только если нужно.

### № 75. Плюсы и недостатки микросервисов и монолитов?
**Монолит:** прост в деплое и отладке, но тяжело масштабировать и внедрять новые технологии.
**Микросервисы:** независимое масштабирование и деплой, но сложная инфраструктура, сетевые задержки и трудный траблшутинг.

### № 76. Протоколы межсервисного взаимодействия?
Синхронные (HTTP/gRPC) и Асинхронные (Message Brokers: Kafka, RabbitMQ).

### № 77. Чем отличается git merge от git rebase?
`merge` — объединяет ветки, сохраняя историю и создавая "merge commit". `rebase` — переписывает историю, делая её линейной (переносит коммиты на верхушку другой ветки).

### № 78. Как откатить изменения в коммите, не удаляя его?
Использовать `git revert <commit>`. Он создаст новый коммит с обратными (противоположными) изменениями.

### № 135. Что такое микросервисы?
Архитектура, при которой приложение разбито на **независимые сервисы**, каждый выполняет определенную задачу и общается с другими через API (REST, gRPC, message brokers).

**Плюсы:**
- Независимое масштабирование каждого сервиса
- Независимый деплой (обновил один сервис — не трогаешь остальные)
- Возможность использовать разные технологии (polyglot)
- Команды автономны (каждая отвечает за свой сервис)

**Минусы:**
- Сложная инфраструктура (оркестрация, мониторинг, трейсинг)
- Сетевые задержки между сервисами
- Сложный траблшутинг (распределенные логи, distributed tracing)
- Проблемы с консистентностью данных (eventual consistency)

### № 136. Что такое монолиты?
Архитектура, при которой **всё приложение — один процесс, один деплой, один код**.

**Плюсы:**
- Простота разработки и отладки (всё в одном месте)
- Простой деплой (один артефакт)
- Нет сетевых задержек между компонентами
- Легко тестировать (интеграционные тесты проще)

**Минусы:**
- Тяжело масштабировать (нужно масштабировать всё целиком)
- Долгий деплой (пересборка всего приложения)
- Блокировка команд (одна команда не может быстро зарелизить фичу из-за других)
- Сложно внедрять новые технологии (всё связано)

**Когда что выбирать:**
- **Монолит** — для стартапов, небольших команд, простых приложений
- **Микросервисы** — для крупных компаний, сложных доменов, когда нужна независимая масштабируемость
